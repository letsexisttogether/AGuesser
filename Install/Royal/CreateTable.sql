DROP TABLE IF EXISTS Users;
CREATE TABLE Users
(
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL,
    Email TEXT NOT NULL
);

DROP TABLE IF EXISTS Rarities;
CREATE TABLE Rarities
(
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT UNIQUE NOT NULL,
    Rank INTEGER NOT NULL
);

DROP TABLE IF EXISTS RangeTypes;
CREATE TABLE RangeTypes
(
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT UNIQUE NOT NULL,
    Rank INTEGER NOT NULL
);

DROP TABLE IF EXISTS Speeds;
CREATE TABLE Speeds
(
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT UNIQUE NOT NULL,
    Rank INTEGER NOT NULL
);

DROP TABLE IF EXISTS Cards;
CREATE TABLE Cards
(
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL
);

DROP TABLE IF EXISTS CardTraits;
CREATE TABLE CardTraits
(
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CardID INTEGER NOT NULL UNIQUE,
    ElixirCost INTEGER NOT NULL,
    RarityID INTEGER NOT NULL,
    CardType TEXT NOT NULL,
    Targets TEXT NOT NULL,
    RangeTypeID INTEGER NOT NULL,
    SpeedID INTEGER NOT NULL,
    ReleaseYear INTEGER NOT NULL,
    FOREIGN KEY (CardID) REFERENCES Cards(ID),
    FOREIGN KEY (RarityID) REFERENCES Rarities(ID),
    FOREIGN KEY (RangeTypeID) REFERENCES RangeTypes(ID),
    FOREIGN KEY (SpeedID) REFERENCES Speeds(ID)
);
